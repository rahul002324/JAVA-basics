public class ifelse {
    public static void main(String[] args) {
        int mark = 50;
        
        if (mark >= 50) {
            System.out.println("pass");
        }else if (mark >= 70) {
            System.out.println("second class");
        } else if (mark >= 90) {
            System.out.println("first class");
        } else {
            System.out.println("fail");
        }
    }
}
